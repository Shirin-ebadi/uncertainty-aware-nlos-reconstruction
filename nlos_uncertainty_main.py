        # 2) اگر weight در عمق‌های مختلف پخش شده باشد:
        #    محل سطح در امتداد ray مبهم‌تر است.
        #
        # بنابراین uncertainty باید با این ابهام فیزیکی
        # رابطه مثبت داشته باشد.
        #
        # detach() باعث می‌شود این loss شاخه reconstruction
        # را تغییر ندهد.
        # =====================================================

        weight_phys = lib['weight'].detach().clamp(
            min=0.0
        )

        # -----------------------------------------------------
        # Depth probability distribution
        # -----------------------------------------------------

        weight_sum = weight_phys.sum(
            dim=-1,
            keepdim=True
        ).clamp(
            min=1e-8
        )

        depth_prob = (
            weight_phys / weight_sum
        ).clamp(
            min=1e-8
        )

        # -----------------------------------------------------
        # Normalized depth entropy
        #
        # entropy بالا:
        # weight روی عمق‌های زیادی پخش شده
        # -----------------------------------------------------

        depth_entropy = -(
            depth_prob *
            torch.log(depth_prob)
        ).sum(
            dim=-1,
            keepdim=True
        )

        n_depth_samples = max(
            int(weight_phys.size(-1)),
            2
        )

        max_entropy = torch.log(
            weight_phys.new_tensor(
                float(n_depth_samples)
            )
        )

