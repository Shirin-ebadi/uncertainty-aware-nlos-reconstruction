import torch
import glob
import os
from pathlib import Path

pth_files = glob.glob(
    "/content/nlos_pretrained/**/last.pth",
    recursive=True
)

# اگر last.pth پیدا نشد، هر pth را بررسی کن
if len(pth_files) == 0:
    pth_files = glob.glob(
        "/content/nlos_pretrained/**/*.pth",
        recursive=True
    )

models = []

print("در حال بررسی مدل‌ها...\n")

for p in pth_files:

    try:
        ckpt = torch.load(
            p,
            map_location="cpu",
            weights_only=False
        )

        config = ckpt.get("config", {})
        opt = config.get("opt", {})

        has_mse = "mse" in opt
        has_poisson = "poisson" in opt

        if has_mse and not has_poisson:
            model_type = "SUPERVISED"

        elif has_mse and has_poisson:
            model_type = "JOINT"

        elif has_poisson:
            model_type = "UNSUPERVISED"

        else:
            model_type = "UNKNOWN"

        models.append({
            "path": p,
            "type": model_type
        })

        print("--------------------------------")
        print("TYPE :", model_type)
        print("PATH :", p)

    except Exception as e:

        print("Could not read:")
        print(p)
        print(e)


if len(models) == 0:
    raise RuntimeError("❌ هیچ مدل سالمی پیدا نشد.")


# اولویت انتخاب:
# supervised > joint > unsupervised

selected = None

for wanted in [
    "SUPERVISED",
    "JOINT",
    "UNSUPERVISED",
    "UNKNOWN"
]:

    for m in models:

        if m["type"] == wanted:
            selected = m
            break

    if selected is not None:
        break


